def ddl(engine: str) -> list[str]:
    """Instructions CREATE TABLE / CREATE INDEX du schéma pour `engine` ('sqlite' ou 'postgres')."""
    if engine not in TYPES:
        raise ValueError(f"moteur inconnu : {engine}")
    out = []
    for name, t in TABLES.items():
        # colonnes de clé NOT NULL dans les deux moteurs (PostgreSQL l'impose ; SQLite le tolérerait)
        cols = [f"{c} {TYPES[engine][typ]}" + (" NOT NULL" if c in t.key and typ != "id" else "") for c, typ in t.columns]
        if t.key != ("id",):
            cols.append(f"PRIMARY KEY ({', '.join(t.key)})")
        cols += [f"UNIQUE ({u})" for u in t.unique]
        out.append(f"CREATE TABLE IF NOT EXISTS {name} ({', '.join(cols)})")
    if engine == "postgres":  # tables invisibles depuis l'API publique de Supabase (seul le serveur s'y connecte)
        out += [f"ALTER TABLE {name} ENABLE ROW LEVEL SECURITY" for name in TABLES]
    return out + list(INDEXES)


# ---------------------------------------------------------------- traduction SQLite → PostgreSQL
_INSERT = re.compile(r"^\s*INSERT\s+(?:OR\s+(REPLACE|IGNORE)\s+)?INTO\s+(\w+)\s*(\(([^)]*)\))?\s*VALUES\s*(.*)$",
                     re.IGNORECASE | re.DOTALL)  # fmt: skip


def _upsert(mode: str | None, name: str, cols: tuple[str, ...]) -> str:
    """Clause ON CONFLICT / RETURNING équivalente au comportement SQLite."""
    if name not in TABLES:
        raise ValueError(f"table inconnue du schéma : {name}")
    t = TABLES[name]
    tail = ""
    if mode == "IGNORE":
        tail = " ON CONFLICT DO NOTHING"
    elif mode == "REPLACE":
        rest = [c for c in cols if c not in t.key]
        sets = ", ".join(f"{c} = EXCLUDED.{c}" for c in rest)
        tail = f" ON CONFLICT ({', '.join(t.key)}) DO " + (f"UPDATE SET {sets}" if rest else "NOTHING")
    if "id" in t.names and t.key == ("id",):
        tail += " RETURNING id"
    return tail


def to_postgres(sql: str) -> str:
    """Traduit une requête écrite pour SQLite en requête PostgreSQL équivalente."""
    if not sql.strip():
        raise ValueError("requête vide")
    out = sql.replace("%", "%%").replace("?", "%s")
    m = _INSERT.match(out)
    if not m:
        return out
    mode, name, explicit, col_list, values = m.groups()
    mode = mode.upper() if mode else None
    if name not in TABLES:
        raise ValueError(f"table inconnue du schéma : {name}")
    cols = tuple(c.strip() for c in col_list.split(",")) if explicit else TABLES[name].names
    return f"INSERT INTO {name} ({', '.join(cols)}) VALUES {values.strip()}{_upsert(mode, name, cols)}"


def _adapt(value: Any) -> Any:
    """Valeur acceptée par les deux moteurs : types numpy → Python, NaN → NULL, booléen → entier."""
    if isinstance(value, np.generic):
        value = value.item()
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, float) and math.isnan(value):
        return None
    return value


def _params(params: Sequence[Any]) -> tuple[Any, ...]:
    """Paramètres adaptés à l'un ou l'autre moteur."""
    return tuple(_adapt(v) for v in params)


# ---------------------------------------------------------------- connexions
def redact(text: str) -> str:
    """Texte (message d'erreur, URL) dont les mots de passe de connexion sont masqués."""
    return re.sub(r"(postgres(?:ql)?://[^:/@\s]+:)[^@\s]+@", r"\1•••@", text)


def database_url() -> str:
    """Chaîne de connexion PostgreSQL (variable DATABASE_URL), vide en mode local SQLite.

    Le pooler Supabase en mode session (port 5432) réserve une connexion serveur par client et plafonne vite
    (15 sur la plus petite offre) ; on passe sur le mode transaction (port 6543), qui les partage.
    """
    url = os.getenv("DATABASE_URL", "").strip()
    if SUPABASE_POOLER in url and SESSION_PORT in url:
        url = url.replace(SESSION_PORT, TRANSACTION_PORT, 1)
    return url


@functools.lru_cache(maxsize=1)
def _pool(url: str) -> ConnectionPool[Any]:
    """Pool de connexions PostgreSQL, créé une seule fois par processus et par URL."""
    if not url.startswith(("postgresql://", "postgres://")):
        raise ValueError("DATABASE_URL doit commencer par postgresql://")
    # essai unique et rapide : un mauvais mot de passe échoue ici avec un message clair,
    # au lieu de laisser le pool réessayer indéfiniment en arrière-plan
    with psycopg.connect(url, connect_timeout=CONNECT_TIMEOUT_S) as probe:
        probe.execute("SELECT 1")
    # prepare_threshold=None : compatible avec le pooler de Supabase (mode transaction)
    pool: ConnectionPool[Any] = ConnectionPool(
        url, min_size=0, max_size=POOL_MAX, max_idle=POOL_MAX_IDLE_S, timeout=POOL_TIMEOUT_S, open=True,
        kwargs={"prepare_threshold": None, "row_factory": dict_row},
    )  # fmt: skip
    atexit.register(pool.close)
    return pool


class Conn:
    """Connexion unifiée : mêmes requêtes (dialecte SQLite) pour SQLite et PostgreSQL."""

    def __init__(self, raw: Any, postgres: bool) -> None:
        """Enveloppe une connexion sqlite3 ou psycopg déjà ouverte."""
        self.raw = raw
        self.postgres = postgres

    def execute(self, sql: str, params: Sequence[Any] = ()) -> Any:
        """Exécute une requête ; renvoie le curseur (rowcount, fetchone, fetchall)."""
        if self.postgres:
            return self.raw.execute(to_postgres(sql), _params(params))
        return self.raw.execute(sql, _params(params))

    def executemany(self, sql: str, rows: Sequence[Sequence[Any]]) -> None:
        """Exécute la requête pour chaque ligne."""
        clean = [_params(r) for r in rows]
        if self.postgres:
            with self.raw.cursor() as cur:
                cur.executemany(to_postgres(sql).replace(" RETURNING id", ""), clean)
            return
        self.raw.executemany(sql, clean)


@contextmanager
def session(path: Path | None = None) -> Iterator[Conn]:
    """Connexion validée à la sortie du bloc et toujours rendue/fermée, même en cas d'erreur.

    `path` force une base SQLite (tests) ; sinon DATABASE_URL décide du moteur.
    """
    url = "" if path is not None else database_url()
    if url:
        with _pool(url).connection() as raw:  # commit à la sortie, rollback en cas d'erreur
            yield Conn(raw, postgres=True)
        return
    raw = sqlite3.connect(str(path or config.DB_PATH), check_same_thread=False, timeout=SQLITE_TIMEOUT_S)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA journal_mode=WAL")
    raw.execute("PRAGMA foreign_keys=ON")
    try:
        yield Conn(raw, postgres=False)
        raw.commit()
    finally:
        raw.close()


def engine() -> str:
    """Moteur utilisé : 'postgres' ou 'sqlite'."""
    return "postgres" if database_url() else "sqlite"


def _sqlite_add_owner(con: Conn) -> None:
    """Ajoute la colonne owner aux bases SQLite créées avant les comptes utilisateurs."""
    cols = {r["name"] for r in con.execute("PRAGMA table_info(portfolios)").fetchall()}
    assert cols, "table portfolios absente"
    if "owner" not in cols:
        con.execute("ALTER TABLE portfolios ADD COLUMN owner TEXT")


def init(path: Path | None = None) -> None:
    """Crée les tables manquantes et charge l'univers des 48 valeurs et les opérations sur titres."""
    with session(path) as con:
        engine_name = "postgres" if con.postgres else "sqlite"
        for stmt in ddl(engine_name):
            con.execute(stmt)
        if not con.postgres:
            _sqlite_add_owner(con)
        for stmt in MIGRATIONS[engine_name]:
            con.execute(stmt)
        con.executemany(
            "INSERT OR REPLACE INTO securities VALUES (?,?,?,?,?)",
            [(t, n, c, s, universe.sika_ticker(t, c)) for t, n, c, s in universe.SECURITIES],
        )
        con.executemany("INSERT OR IGNORE INTO corporate_actions VALUES (?,?,?)", universe.CORPORATE_ACTIONS)


def df(sql: str, params: Sequence[Any] = (), path: Path | None = None) -> pd.DataFrame:
    """Résultat d'une requête paramétrée sous forme de DataFrame (colonnes présentes même sans ligne)."""
    with session(path) as con:
        cur = con.execute(sql, params)
        cols = [d[0] for d in cur.description or ()]
        rows = cur.fetchall()
    if con.postgres:
        return pd.DataFrame([tuple(r.values()) for r in rows], columns=cols)
    return pd.DataFrame([tuple(r) for r in rows], columns=cols)


def execute(sql: str, params: Sequence[Any] = (), path: Path | None = None) -> int:
    """Exécute une requête paramétrée ; renvoie l'identifiant de la ligne insérée (0 sinon)."""
    with session(path) as con:
        cur = con.execute(sql, params)
        if con.postgres:
            row = cur.fetchone() if cur.description else None
            return int(row["id"]) if row else 0
        return int(cur.lastrowid or 0)


def executemany(sql: str, rows: Sequence[Sequence[Any]], path: Path | None = None) -> None:
    """Exécute une requête paramétrée pour chaque ligne de `rows`, dans une seule transaction."""
    with session(path) as con:
        con.executemany(sql, rows)


def get_setting(key: str, default: Any = None, path: Path | None = None) -> Any:
    """Réglage enregistré (JSON), ou `default` s'il n'existe pas."""
    with session(path) as con:
        row = con.execute("SELECT value FROM settings WHERE key=?", (key,)).fetchone()
    return json.loads(row["value"]) if row else default


def set_setting(key: str, value: Any, path: Path | None = None) -> None:
    """Enregistre un réglage (sérialisé en JSON)."""
    execute("INSERT OR REPLACE INTO settings VALUES (?,?)", (key, json.dumps(value)), path)


def now_utc() -> str:
    """Horodatage UTC au format 'AAAA-MM-JJ HH:MM:SS' (identique dans les deux moteurs)."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


def mark_update(what: str, path: Path | None = None) -> None:
    """Horodate la dernière mise à jour d'un type de données (cours, veille, BOC…)."""
    execute("INSERT OR REPLACE INTO updates VALUES (?, ?)", (what, now_utc()), path)


def last_update(what: str, path: Path | None = None) -> str | None:
    """Horodatage de la dernière mise à jour d'un type de données, ou None."""
    with session(path) as con:
        row = con.execute("SELECT at FROM updates WHERE what=?", (what,)).fetchone()
    return str(row["at"]) if row else None
