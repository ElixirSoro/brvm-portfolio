@dataclass(frozen=True)
class Table:
    """Une table : colonnes (nom, type logique) dans l'ordre, clé primaire, colonnes uniques."""

    columns: tuple[tuple[str, str], ...]
    key: tuple[str, ...]
    unique: tuple[str, ...] = ()

    @property
    def names(self) -> tuple[str, ...]:
        """Noms des colonnes dans l'ordre du schéma."""
        return tuple(c for c, _ in self.columns)


def _cols(spec: str) -> tuple[tuple[str, str], ...]:
    """'a text, b real' → (('a', 'text'), ('b', 'real'))."""
    out = tuple((p.split()[0], p.split()[1]) for p in spec.split(","))
    assert all(t in TYPES["sqlite"] for _, t in out), f"type inconnu dans {spec}"
    return out


