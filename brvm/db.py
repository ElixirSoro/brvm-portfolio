"""Base de données : SQLite en local, PostgreSQL (Supabase) en ligne.

Contrat
- Moteur : PostgreSQL si la variable DATABASE_URL est définie, sinon le fichier SQLite config.DB_PATH.
- Le reste du code écrit ses requêtes dans le dialecte SQLite (`?`, INSERT OR REPLACE / OR IGNORE) ;
  `to_postgres` les traduit à l'identique pour PostgreSQL à partir du schéma déclaré dans TABLES.
- Paramètres : types numpy convertis en types Python, NaN en NULL, booléens en entiers.
- Erreurs : DB_ERRORS regroupe les erreurs des deux moteurs ; une requête vers une table inconnue
  du schéma lève ValueError lors de la traduction.
"""

